import { existsSync, readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';

const variables = {
  domain: 'AUTH0_DOMAIN',
  clientId: 'AUTH0_CLIENT_ID',
  audience: 'AUTH0_AUDIENCE',
};
const envFile = new URL('../.env', import.meta.url);

// Node's native loader preserves existing process variables, including empty ones.
if (
  Object.values(variables).some((name) => process.env[name] === undefined) &&
  existsSync(envFile)
) {
  process.loadEnvFile(fileURLToPath(envFile));
}

const missing = Object.values(variables).filter((name) => !process.env[name]?.trim());
if (missing.length > 0) {
  console.error(
    `Missing required Auth0 environment variables: ${missing.join(', ')}. Set them in the process environment or frontend/.env.`,
  );
  process.exit(1);
}

// Whitelist public SPA settings. 
const settings = Object.fromEntries(
  Object.entries(variables).map(([property, name]) => [property, process.env[name].trim()]),
);
const output = new URL('../src/app/core/auth.config.generated.ts', import.meta.url);
const source =
  '// Generated by scripts/generate-auth-config.mjs. Do not edit or commit.\n' +
  `export const auth0Settings = ${JSON.stringify(settings, null, 2)} as const;\n`;

if (!existsSync(output) || readFileSync(output, 'utf8') !== source) {
  writeFileSync(output, source, 'utf8');
}
